               	['PRODUCT_BUNDLE_IDENTIFIER'] = game_project and game_project.bundle_id or settings.bundle_identifier,
               	['CODE_SIGN_IDENTITY'] = 'Mac Developer',
               	['DEVELOPMENT_TEAM'] = settings.developer_team
