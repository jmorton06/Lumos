			local lmproj_resource = ios_project_dir .. "/" .. (ios_lmproj_name or (ios_project_folder .. ".lmproj"))
			xcodebuildresources
			{
				"../Resources/AppIcons/Assets.xcassets",
				"../Lumos/Assets/Shaders",
				ios_project_dir .. "/Assets.lpak",
